def setup_logging(log_file):
    # Create a file handler that logs to the specified file
    if log_file:
        # Convert to absolute path if it's not already
        if not os.path.isabs(log_file):
            log_file = os.path.abspath(log_file)

        # Make sure the directory exists
        log_dir = os.path.dirname(log_file)
        if log_dir and not os.path.exists(log_dir):
            os.makedirs(log_dir, exist_ok=True)

        # Reset any existing handlers first
        for handler in logging.root.handlers[:]:
            logging.root.removeHandler(handler)

        # Configure the root logger with both file and console handlers
        logging.basicConfig(
            level=logging.INFO,
            format="%(asctime)s - %(levelname)s - %(message)s",
            handlers=[
                logging.FileHandler(log_file, mode="a"),  # Append mode
                logging.StreamHandler(),  # Also log to console
            ],
        )
        logging.info(f"Logging is set up. Writing to {log_file}")
    else:
        # If no log file provided, just log to console
        logging.basicConfig(
            level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s"
        )
        logging.info("Logging is set up (console only).")



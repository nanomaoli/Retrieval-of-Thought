def convert_json_to_chat_template(json_file_path):
    """
    Converts a JSON file with system_prompt and few_shot_examples
    to the OpenAI chat completions message format.
    """
    with open(json_file_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    chat_messages = []

    # Add system prompt
    if "system_prompt" in data and data["system_prompt"]:
        chat_messages.append({"role": "system", "content": data["system_prompt"]})

    # Add few-shot examples
    if "few_shot_examples" in data:
        for example in data["few_shot_examples"]:
            if "user" in example and example["user"]:
                chat_messages.append({"role": "user", "content": example["user"]})
            if "assistant" in example and example["assistant"]:
                chat_messages.append(
                    {"role": "assistant", "content": example["assistant"]}
                )

    return chat_messages


def extract_and_validate_answer(output_text, expected_answer_str, problem_id):
    """
    Extracts the answer from the model\'s output text and validates it against the expected answer.

    Args:
        output_text (str): The text generated by the model.
        expected_answer_str (str): The expected answer.
        problem_id (str): The ID of the problem for logging.

    Returns:
        - str: The extracted answer string.
        - bool: Whether the extracted answer is correct.
    """
    # Extract the boxed answer
    output_text = output_text.encode("unicode_escape").decode()
    match = re.search(r"\\\\boxed\{(.*?)\}", output_text)
    extracted_answer_str = None
    potential_answer = None
    if match:
        extracted_answer_str = match.group(1).strip()
        extracted_answer_str = re.sub(r"[$, ]", "", extracted_answer_str)
        extracted_answer_str = re.sub(r"^[^\d.-]+|[^\d.-]+$", "", extracted_answer_str)
    else:
        # Fallback: try to find text after the last "="
        last_equal_index = output_text.rfind("=")
        if last_equal_index != -1:
            # Extract text after the last "="
            potential_answer = output_text[last_equal_index + 1 :].strip()
            # Further clean up: remove any remaining LaTeX or common non-numeric text
            potential_answer = re.sub(r"\\\\text\{.*?\}", "", potential_answer)
            potential_answer = re.sub(
                r"\\\\frac\{.*?\}\{.*?\}", "", potential_answer
            )  # Basic fraction removal
            potential_answer = re.sub(
                r"[^0-9.-]", "", potential_answer
            )  # Keep only digits, dot, and minus
        if potential_answer:
            extracted_answer_str = potential_answer

    # If still no answer, try to find the last number in the string
    if not extracted_answer_str:
        numbers = re.findall(r"[-+]?\d*\.\d+|[-+]?\d+", output_text)
        if numbers:
            extracted_answer_str = numbers[-1]

    is_correct = False
    if extracted_answer_str is not None:  # Check if an answer was actually extracted
        logging.info(
            f"Extracted answer is not None: '{extracted_answer_str}' for problem {problem_id}"
        )
        try:
            # Attempt numeric conversion for robust comparison
            # Clean the extracted string: remove common currency symbols, commas, spaces
            cleaned_extracted_str = re.sub(r"[$, ]", "", str(extracted_answer_str))
            # Further clean to keep only digits, decimal point, and potential minus sign
            cleaned_extracted_str = re.sub(r"[^\d.-]", "", cleaned_extracted_str)

            if not cleaned_extracted_str or cleaned_extracted_str in [
                "-",
                ".",
            ]:  # Handle empty or invalid string after cleaning
                raise ValueError(
                    f"Extracted answer '{extracted_answer_str}' became invalid after cleaning: '{cleaned_extracted_str}'"
                )
            extracted_num = int(round(float(cleaned_extracted_str)))

            # Clean and convert expected_answer_str similarly for robust comparison
            cleaned_expected_str = re.sub(r"[$, ]", "", str(expected_answer_str))
            cleaned_expected_str = re.sub(r"[^\d.-]", "", cleaned_expected_str)
            if not cleaned_expected_str or cleaned_expected_str in ["-", "."]:
                raise ValueError(
                    f"Expected answer '{expected_answer_str}' became invalid after cleaning: '{cleaned_expected_str}'"
                )
            expected_num = int(round(float(cleaned_expected_str)))

            is_correct = extracted_num == expected_num
        except ValueError as e:
            # Fallback to string comparison if numeric conversion fails for EITHER string
            logging.warning(
                f"WARN ({problem_id}): Could not convert extracted answer '{extracted_answer_str}' or expected '{expected_answer_str}' to number for precise comparison due to '{e}'. Using string comparison as fallback."
            )
            is_correct = (
                str(extracted_answer_str).strip() == str(expected_answer_str).strip()
            )
        except (
            Exception
        ) as conv_e:  # Catch any other unexpected error during conversion
            logging.error(
                f"ERROR ({problem_id}): Error during answer conversion (Ext: '{extracted_answer_str}', Exp: '{expected_answer_str}'): {conv_e}. Marking incorrect."
            )
            is_correct = False
    elif (
        str(extracted_answer_str).strip() == str(expected_answer_str).strip()
    ):  # Handles case where extracted_answer_str might be None and expected is "None" or similar
        is_correct = True
    else:
        logging.warning(
            f"WARN ({problem_id}): No answer extracted from model output, or extracted does not match expected when None."
        )
        # is_correct remains False

    return extracted_answer_str, is_correct



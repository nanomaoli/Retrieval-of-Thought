def load_metrics_as_dict(file_path: str) -> Dict[str, Any]:
    """
    Loads a Prometheus metrics file into a dictionary where keys are metric names.
    """
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            all_families = list(text_string_to_metric_families(f.read()))

            metrics_dict = {}
            for family in all_families:
                # For histograms, samples have different names (_bucket, _count, _sum)
                if family.type == "histogram":
                    for sample in family.samples:
                        metrics_dict[sample.name] = sample
                else:
                    # For other types, the family name is the key
                    metrics_dict[family.name] = family
            return metrics_dict

    except FileNotFoundError:
        print(f"Error: File not found at '{file_path}'")
        return {}


def print_required_metrics(metrics_file: str):

    # The specific metrics you want to print
    attributes_to_print = [
        "vllm:request_prompt_tokens_sum",
        "vllm:request_generation_tokens_sum",
        "vllm:e2e_request_latency_seconds_count",
        "vllm:e2e_request_latency_seconds_sum",
        "vllm:time_to_first_token_seconds_count",
        "vllm:time_to_first_token_seconds_sum",
        "vllm:request_inference_time_seconds_sum",
        "vllm:request_prefill_time_seconds_sum",
        "vllm:request_decode_time_seconds_sum",
    ]

    metrics_data = load_metrics_as_dict(metrics_file)

    if metrics_data:
        print("--- Required Metric Values ---")
        logging.info("------------- System Metrics -------------")
        for metric_name in attributes_to_print:

            if metric_name in metrics_data:
                metric_object = metrics_data[metric_name]
                # For histograms, the object is a Sample and has a .value
                # For counters/gauges, it's a MetricFamily, so we get the value from its first sample.
                if hasattr(metric_object, "value"):
                    value = metric_object.value
                elif hasattr(metric_object, "samples") and metric_object.samples:
                    value = metric_object.samples[0].value
                else:
                    value = "N/A"

                print(f"{metric_name}: {value}")
                logging.info(f"{metric_name}: {value}")
            else:
                print(f"{metric_name}: Not found")
                logging.warning(f"{metric_name}: Not found")
    else:
        print("Could not load or parse the metrics file.")


def make_template(df):
    templ = "Name: {}\nTags: {}\nDescription: {}\nsteps:\n{}"
    df["steps_templ"] = df["steps"].apply(
        lambda steps: "\n".join(
            [
                f"{i+1}. Step: {step['step']}. Detail: {step['detail']}"
                for i, step in enumerate(steps)
            ]
        )
    )
    df["template"] = df.apply(
        lambda row: templ.format(
            row["name"],
            ", ".join(i for i in row["tags"]),
            row["description"],
            row["steps_templ"],
        ),
        axis=1,
    )


def rag_top_1(bi_encoder, prob, templates, corpus_embeddings):
    start = time.perf_counter()
    question_embedding = bi_encoder.encode(prob, convert_to_tensor=True)
    hits = util.semantic_search(question_embedding, corpus_embeddings, top_k=1)
    hits = hits[0]
    result = {
        "search_results": [
            {"score": hit["score"], "text": templates[hit["corpus_id"]]} for hit in hits
        ]
    }
    result = result["search_results"][0]["text"]
    template = result.split("steps:")[1].strip()
    end = time.perf_counter()
    time_to_gen_templ = end - start
    return template, time_to_gen_templ
